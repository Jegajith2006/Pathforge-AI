def enrich_assessment_questions():
    print("Enriching assessment questions...")
    init_db()
    session = SessionLocal()

    # 1. Database insertion
    existing_qids = set(r[0] for r in session.query(AssessmentQuestion.question_id).all())
    added_to_db = 0

    for q_data in NEW_QUESTIONS:
        qid = q_data["question_id"]
        if qid not in existing_qids:
            q_obj = AssessmentQuestion(
                question_id=qid,
                career_id=q_data["career_id"],
                skill_id=q_data["skill_id"],
                difficulty=q_data["difficulty"],
                question_type=q_data["question_type"],
                question=q_data["question"],
                option_a=q_data["option_a"],
                option_b=q_data["option_b"],
                option_c=q_data["option_c"],
                option_d=q_data["option_d"],
                correct_answer=q_data["correct_answer"],
                explanation=q_data["explanation"],
                weight=q_data["weight"],
            )
            session.add(q_obj)
            existing_qids.add(qid)
            added_to_db += 1

    session.commit()
    session.close()
    print(f"[OK] Added {added_to_db} questions to SQLite database.")

    # 2. Append to CSV files
    csv_paths = [
        Path("datasets/09_assessment_questions.csv"),
        Path("datasets/assessment_questions.csv"),
    ]

    for p in csv_paths:
        if not p.exists():
            continue
        df = pd.read_csv(p)
        csv_existing_qids = set(df["question_id"].astype(str))
        rows_to_add = [q for q in NEW_QUESTIONS if q["question_id"] not in csv_existing_qids]
        if rows_to_add:
            new_df = pd.DataFrame(rows_to_add)
            combined = pd.concat([df, new_df], ignore_index=True)
            combined.to_csv(p, index=False)
            print(f"[OK] Added {len(rows_to_add)} questions to {p}")
        else:
            print(f"[OK] {p} already up-to-date.")


if __name__ == "__main__":
    enrich_assessment_questions()
