// Helper to look up specific company/role
export const getCompanyMatch = (companyName, roleTitle) => {
  if (!companyName) return companyMatchData[0];
  const normalizedComp = companyName.trim().toLowerCase();
  
  if (roleTitle) {
    const normalizedRole = roleTitle.trim().toLowerCase();
    const exactMatch = companyMatchData.find(
      (m) =>
        m.company.toLowerCase() === normalizedComp &&
        m.role.toLowerCase() === normalizedRole
    );
    if (exactMatch) return exactMatch;
  }

  const companyMatches = companyMatchData.filter(
    (m) => m.company.toLowerCase() === normalizedComp
  );
  return companyMatches[0] || companyMatchData[0];
};

