// 18 weeks of realistic GitHub-style heatmap data
export const generateHeatmapData = (): HeatmapDay[] => {
  const data: HeatmapDay[] = [];
  const today = new Date('2025-06-12');
  const totalDays = 18 * 7;

  for (let i = totalDays - 1; i >= 0; i--) {
    const d = new Date(today);
    d.setDate(d.getDate() - i);
    const dateStr = d.toISOString().split('T')[0];

    // Simulate realistic activity (higher on weekdays, periodic study sprints)
    const dayOfWeek = d.getDay(); // 0 is Sunday, 6 is Saturday
    let count = 0;
    let hours = 0;
    const activities: string[] = [];

    const isSprint = (i > 10 && i < 35) || (i > 60 && i < 80);
    const rand = Math.random();

    if (dayOfWeek !== 0 && rand > 0.25) {
      if (rand > 0.85 || isSprint) {
        count = 4;
        hours = 3.5;
        activities.push('SQL Window Functions sprint (2 hrs)', 'Completed Jupyter Notebook project (1.5 hrs)');
      } else if (rand > 0.6) {
        count = 3;
        hours = 2.5;
        activities.push('Pandas data cleaning lab (1.5 hrs)', 'Reviewed mentor feedback (1 hr)');
      } else if (rand > 0.35) {
        count = 2;
        hours = 1.5;
        activities.push('Completed 3 SQL practice drills (1.5 hrs)');
      } else {
        count = 1;
        hours = 0.75;
        activities.push('Read Tableau LOD calculations article (45 min)');
      }
    } else if (dayOfWeek === 0 && rand > 0.5) {
      count = 2;
      hours = 2.0;
      activities.push('Weekly project architecture review & commit (2 hrs)');
    }

    data.push({
      date: dateStr,
      count,
      hours,
      activities,
    });
  }

  return data;
};

